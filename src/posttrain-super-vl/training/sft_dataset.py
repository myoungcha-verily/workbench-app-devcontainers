"""Agent-trajectory SFT data for the NeMo AutoModel VLM recipe (Nemotron 3.5 Super VL, text-only).

Input rows come from eval-bench harness/export_sft.py: {"id", "messages" (OpenAI chat format with tool_calls and tool
results), "tools" (JSON string of OpenAI tool schemas), "weight", "split", "meta"}. train_weighted.jsonl already repeats
examples by weight, so the loss itself is unweighted.

Why a custom collate instead of nemotron_omni_collate_fn: that collate renders the chat template without `tools`, and
the Super VL template renders tool calls with `tool_call.arguments|items`, which needs a mapping while OpenAI-format data
(and AutoModel's agent_chat converter) carry arguments as JSON strings. Here the arguments are decoded, the template is
rendered with the tool schemas, and labels cover only assistant turns (from the `<|im_start|>assistant\\n` marker through
`<|im_end|>`), optionally without the empty `<think></think>` block the template inserts when a turn has no reasoning
(the TRN trajectories have none; supervising it would teach the model to skip thinking).

Config usage (AutoModel YAML):
  dataset:    {_target_: sft_dataset.make_agent_sft_dataset, file: train_weighted.jsonl}
  dataloader: {collate_fn: {_target_: sft_dataset.agent_collate_fn, max_length: 32768, pad_to_multiple: 128}}
The directory comes from SFT_DATA_DIR (set by run_job.py) unless `data_dir` is given.
"""
import copy
import json
import os
import pathlib
from typing import Any, Dict, List, Sequence

import torch

ASSISTANT_MARKER = "<|im_start|>assistant\n"
END = "<|im_end|>"
EMPTY_THINK = "<think></think>"


def make_agent_sft_dataset(file: str = "train_weighted.jsonl", data_dir: str | None = None, max_tokens: int | None = None,
                           limit_dataset_samples: int | None = None, **kwargs) -> List[Dict[str, Any]]:
    """Plain list of rows (map-style dataset). max_tokens drops rows whose exported length (meta.n_tokens) exceeds it,
    so a 32k config can reuse a 64k export without truncating any trajectory."""
    d = pathlib.Path(data_dir or os.environ.get("SFT_DATA_DIR", "."))
    rows = []
    for line in open(d / file):
        r = json.loads(line)
        if max_tokens and json.loads(r.get("meta") or "{}").get("n_tokens", 0) > max_tokens:
            continue
        rows.append({"id": r["id"], "messages": r["messages"], "tools": r.get("tools")})
        if limit_dataset_samples and len(rows) >= limit_dataset_samples:
            break
    if not rows:
        raise ValueError(f"no rows in {d / file} (max_tokens={max_tokens})")
    return rows


def to_template_messages(messages: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    out = copy.deepcopy(list(messages))
    for m in out:
        for c in m.get("tool_calls") or []:
            fn = c.get("function", c)
            if isinstance(fn.get("arguments"), str):
                fn["arguments"] = json.loads(fn["arguments"] or "{}")
    return out


def render(example: Dict[str, Any], tokenizer) -> str:
    tools = example.get("tools")
    tools = json.loads(tools) if isinstance(tools, str) else tools
    return tokenizer.apply_chat_template(to_template_messages(example["messages"]), tools=tools or None, tokenize=False)


def assistant_labels(ids: List[int], marker: List[int], end_id: int, empty_think: List[int] | None) -> List[int]:
    labels = [-100] * len(ids)
    n, k, i = len(ids), len(marker), 0
    while i <= n - k:
        if ids[i:i + k] == marker:
            start = i + k
            if empty_think and ids[start:start + len(empty_think)] == empty_think:
                start += len(empty_think)  # template-inserted, never generated by the model at inference
            j = start
            while j < n and ids[j] != end_id:
                j += 1
            j = min(j + 1, n)  # include <|im_end|> so the model learns to stop the turn
            labels[start:j] = ids[start:j]
            i = j
        else:
            i += 1
    return labels


def agent_collate_fn(examples: Sequence[Dict[str, Any]], processor, max_length: int | None = None,
                     pad_to_multiple: int = 128, mask_empty_think: bool = True) -> Dict[str, torch.Tensor]:
    tok = getattr(processor, "tokenizer", processor)
    marker = tok.encode(ASSISTANT_MARKER, add_special_tokens=False)
    end_id = tok.convert_tokens_to_ids(END)
    empty = tok.encode(EMPTY_THINK, add_special_tokens=False) if mask_empty_think else None
    seqs, labs = [], []
    for ex in examples:
        ids = tok(render(ex, tok), add_special_tokens=False)["input_ids"]
        lab = assistant_labels(ids, marker, end_id, empty)
        if max_length and len(ids) > max_length:  # export filters by length, so this should not trigger
            ids, lab = ids[:max_length], lab[:max_length]
        seqs.append(ids)
        labs.append(lab)
    L = max(len(s) for s in seqs)
    L = -(-L // pad_to_multiple) * pad_to_multiple + 1  # +1: inputs/labels are shifted by one below
    pad = tok.pad_token_id if tok.pad_token_id is not None else 0
    input_ids = torch.full((len(seqs), L), pad, dtype=torch.long)
    labels = torch.full((len(seqs), L), -100, dtype=torch.long)
    attn = torch.zeros((len(seqs), L), dtype=torch.long)
    for b, (s, l) in enumerate(zip(seqs, labs)):
        input_ids[b, :len(s)] = torch.tensor(s)
        labels[b, :len(l)] = torch.tensor(l)
        attn[b, :len(s)] = 1
    # same convention as nemotron_omni_collate_fn: labels[t] is the target for input t
    return {"input_ids": input_ids[:, :-1], "attention_mask": attn[:, :-1], "labels": labels[:, 1:]}
